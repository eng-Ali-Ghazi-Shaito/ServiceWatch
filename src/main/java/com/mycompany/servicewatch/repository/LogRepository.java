package com.mycompany.servicewatch.repository;

import com.mycompany.servicewatch.database.DataBaseConnection;
import com.mycompany.servicewatch.model.LogRecord;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;

import com.mycompany.servicewatch.model.Severity;

import java.util.ArrayList;
import java.util.List;

public class LogRepository {

    public long insert(LogRecord log) throws SQLException {

        String sql = """
                INSERT INTO logs
                (
                    application_id,
                    event_timestamp,
                    receipt_timestamp,
                    severity,
                    message
                )
                VALUES (?, ?, ?, ?, ?)
                """;

        try (
            Connection connection = DataBaseConnection.getConnection();
            PreparedStatement statement =
                    connection.prepareStatement(
                            sql,
                            // Ask MySQL to return the auto-generated ID of the inserted log.
                            PreparedStatement.RETURN_GENERATED_KEYS
                    )
        ) {
            statement.setLong(1, log.getApplicationId());
            statement.setTimestamp(2, log.getEventTimestamp());
            statement.setTimestamp(3, log.getReceiptTimestamp());
            statement.setString(4, log.getSeverity().name());
            statement.setString(5, log.getMessage());

            statement.executeUpdate();
//asks for the ID generated by MySQL.
            try (ResultSet keys = statement.getGeneratedKeys()) {
                //moves to the returned key row
                if (keys.next()) {
                    //reads the first column  which is the generated log ID
                    return keys.getLong(1);
                }
            }
        }

        throw new SQLException("Log ID was not generated");
    }
    
    
    
    public List<LogRecord> findAll() throws SQLException {

    String sql = """
            SELECT id,
                   application_id,
                   event_timestamp,
                   receipt_timestamp,
                   severity,
                   message
            FROM logs
            ORDER BY event_timestamp DESC
            """;

    List<LogRecord> logs = new ArrayList<>();

    try (
        Connection connection = DataBaseConnection.getConnection();
        PreparedStatement statement =
                connection.prepareStatement(sql);
        ResultSet result = statement.executeQuery()
    ) {
        while (result.next()) {

            LogRecord log = new LogRecord(
                    result.getLong("id"),
                    result.getLong("application_id"),
                    result.getTimestamp("event_timestamp"),
                    result.getTimestamp("receipt_timestamp"),
                    Severity.valueOf(
                            result.getString("severity")
                    ),
                    result.getString("message")
            );

            logs.add(log);
        }
    }

    return logs;
}
}